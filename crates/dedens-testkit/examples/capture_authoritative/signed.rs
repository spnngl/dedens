//! The `signed` stage: Knot's offline signer signs a zone with an NSEC3 chain, and both servers answer the signed zone.
//!
//! The one source of an NSEC3 chain signed by a real signer, which `dedens-zone`'s tests hold the validator to
//! (D209): the RFC 5155 appendix zones' keys are 512 bits.

use std::path::Path;

use dedens_proto::{RecordType, ZoneEntry, ZoneReader};

use crate::engine::{self, KNOT_IMAGE, Mount};
use crate::servers::{self, Scratch};
use crate::zones::{self, SIGNED, UNSIGNED};
use crate::{Result, write};

/// The time the signer is told it is, 2026-05-28 20:26:40 UTC: the signatures' inception and expiry follow from it
/// (Knot's: 90 minutes before, 14 days after), and the validator of the tests runs at it.
const SIGNED_AT: u64 = 1_780_000_000;

/// Knot's configuration: ECDSA P-256, NSEC3 without iterations or salt, opt-out, one zone-signing and one key-signing
/// key (the policy's default), generated by the signer.
const CONFIG: &str = "server:\n  rundir: /tmp\n\
    policy:\n  - id: p\n    algorithm: ecdsap256sha256\n    nsec3: on\n    nsec3-iterations: 0\n    \
    nsec3-salt-length: 0\n    nsec3-opt-out: on\n\
    template:\n  - id: default\n    storage: /zones\n\
    zone:\n  - domain: example.\n    file: source.zone\n    dnssec-signing: on\n    dnssec-policy: p\n";

/// Signs [`UNSIGNED`] into `zones/nsec3_signed.zone`, and captures both servers' answers on it.
pub(crate) fn signed(dir: &Path) -> Result<()> {
    let testdata = dir.parent().ok_or("no testdata directory")?;
    let records = UNSIGNED.load(testdata)?;
    let scratch = Scratch::new("signed")?;
    scratch.put(
        "source.zone",
        &zones::render(&records, &format!("{}, as Knot reads it.", UNSIGNED.file)),
    )?;
    scratch.put("knot.conf", CONFIG)?;
    std::fs::create_dir(scratch.path().join("out"))?;
    let at = SIGNED_AT.to_string();
    let output = engine::tool(
        KNOT_IMAGE,
        "kzonesign",
        &[
            "-c",
            "/zones/knot.conf",
            "-t",
            &at,
            "-o",
            "/zones/out",
            "example.",
        ],
        &[Mount {
            host: scratch.path(),
            container: "/zones",
            writable: true,
        }],
        None,
    )?;
    let log = engine::text(&output);
    let text = std::fs::read(scratch.path().join("out/source.zone"))
        .map_err(|error| format!("kzonesign wrote no zone ({error}): {log}"))?;
    let mut signed = Vec::new();
    for entry in ZoneReader::new(&text, Some(SIGNED.apex()?)) {
        match entry? {
            ZoneEntry::Record(decoded) => signed.push(decoded.record),
            _ => return Err("a zone entry that is no record".into()),
        }
    }
    if !signed
        .iter()
        .any(|record| record.rtype() == RecordType::NSEC3)
    {
        return Err(format!("kzonesign signed no NSEC3 chain: {log}").into());
    }
    write(
        &dir.join("zones/nsec3_signed.zone"),
        zones::render(
            &signed,
            &format!(
                "{}, signed by Knot's kzonesign at {SIGNED_AT} \
                 (ECDSA P-256, NSEC3 with 0 iterations, no salt, opt-out).",
                UNSIGNED.file
            ),
        )
        .as_bytes(),
    )?;
    servers::capture(dir, &SIGNED, &servers::versions()?)
}
